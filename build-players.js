/* ---- تحويل المركز العربي لكود الفيفا ---- */
function posCode(p) {
  const s = String(p || '');
  if (s.includes('حارس')) return 'GK';
  if (s.includes('مدافع') || s.includes('ظهير') || s.includes('ليبرو')) return 'DF';
  if (s.includes('وسط') || s.includes('صانع')) return 'MF';
  if (s.includes('مهاجم') || s.includes('جناح')) return 'FW';
  return 'MF';
}

/* ---- سعر بالملايين من التقييم ---- */
function valueOf(r) {
  if (r >= 89) return 90;
  if (r >= 86) return 65;
  if (r >= 83) return 45;
  if (r >= 80) return 30;
  if (r >= 77) return 20;
  if (r >= 74) return 13;
  if (r >= 71) return 9;
  return 6;
}


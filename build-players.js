/* ---- هاش حتمي للباقي ---- */
function hashStr(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

const db = JSON.parse(fs.readFileSync(SRC, 'utf8'));
let missing = 0;
let starCount = 0;
db.players.forEach((p) => {
  const star = STARS[p.n];
  let r, pos;
  if (star) {
    [r, pos] = star;
    starCount++;
  } else {
    const h = hashStr(p.n);
    r = 67 + (h % 14); // 67..80
    if (h % 7 === 0 && posCode(p.p) === 'MF') r += 2; // بعض صانعي الألعاب شوية أعلى
    pos = posCode(p.p);
  }
  p.r = r;
  p.pos = pos;
  p.v = valueOf(r);
});

